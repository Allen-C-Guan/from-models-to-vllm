def annotate(name, lines, start):
    notes=NOTES[name];assert all(start<=n<start+len(lines) for n in notes)
    result=[]
    for n,line in enumerate(lines,start):
        if n in notes:
            indent=line[:len(line)-len(line.lstrip())]
            result.append(indent+'# 【解读】'+notes[n])
        result.append(line)
    return '\n'.join(result)
